def enhance_final_notebook(original: dict) -> dict:
    """Return a complete patched notebook, leaving `original` untouched."""
    final = copy.deepcopy(original)
    notebook_cells = final["cells"]
    if any(MARKER in _source(c) for c in notebook_cells):
        return final

    _set(
        notebook_cells[0],
        _source(notebook_cells[0]).replace(
            "(branch `main`)",
            "(integration review branch `integration_pawan_ashley`; merge "
            "only after approval)",
        )
        + "\n**Integration status:** October 18, 2026; 155 local tests "
        "passed, and one enhanced NVDA run completed. Live notebook "
        "execution remains required.\n",
    )
    notebook_cells.insert(
        1,
        _md(
            f"<!-- {MARKER} -->\n"
            "**Execution instructions:** This is the *single consolidated* "
            "Colab notebook "
            "for the combined Nicole, Ashley, and Pawan branch. Push "
            "`integration_pawan_ashley` to GitHub **before** Colab clones it. "
            "Run all cells to generate fresh results. This source notebook "
            "contains no current live outputs; historical scores are "
            "explicitly "
            "identified as earlier observations. The setup uses an isolated "
            "Drive "
            "repository because the memory experiment deletes that copy's "
            "`memory/notes.json`. Do not run it in the team's shared working "
            "copy.\n"
        ),
    )

    setup_idx = _find(notebook_cells, 'BRANCH = "main"')
    setup_src = _source(notebook_cells[setup_idx])
    setup_src = setup_src.replace(
        'BRANCH = "main"', 'BRANCH = "integration_pawan_ashley"'
    )
    setup_src = setup_src.replace(
        'REPO = "/content/drive/MyDrive/equity-agent"',
        'REPO = "/content/drive/MyDrive/'
        'equity-agent-pawan-integration-review"',
    )
    _set(notebook_cells[setup_idx], setup_src)

    # Use the enhanced evaluator for each research run, including C1 and the
    # memory ablation. Keep the original LLM grader and no-tools baseline.
    count = 0
    for cell in notebook_cells:
        if cell["cell_type"] != "code":
            continue
        source = _source(cell)
        if "run_agent(" not in source:
            continue
        # Precisely update original one-line calls in the supplied notebook.
        for old, new in {
            "run_agent(TICKER)": "run_agent(TICKER, reviewed_evaluation=True)",
            "run_agent(t)": "run_agent(t, reviewed_evaluation=True)",
            "run_agent(TICKER, use_memory=False)": "run_agent(TICKER, "
            "use_memory=False, "
            "reviewed_evaluation=True)",
            "run_agent(TICKER, use_memory=True)": "run_agent(TICKER, "
            "use_memory=True, "
            "reviewed_evaluation=True)",
        }.items():
            n = source.count(old)
            count += n
            source = source.replace(old, new)
        _set(cell, source)
    if count != 5:
        raise ValueError(
            f"Expected 5 calls to run_agent to update, found {count}"
        )

    b7 = _find(notebook_cells, "## B7. Evaluator-optimizer loop")
    _set(notebook_cells[b7], B7_NOTE)
    b8 = _find(notebook_cells, "## B8. Final report")
    notebook_cells.insert(b8, _code(B7_AUDIT))

    # Build C1 integrated results, including numerical coverage and accepted
    # status, and use the selected draft score (not simply last history row).
    c1_idx = _find(
        notebook_cells, '"agent_final": st["history"][-1]["average"]'
    )
    c1_src = _source(notebook_cells[c1_idx])
    c1_src = c1_src.replace(
        '"agent_final": st["history"][-1]["average"]',
        '"agent_final": st["evaluation"].average,\n'
        '            "accepted": st["accepted"],\n'
        '            "selected_iteration": st["selected_iteration"],\n'
        '            "numeric_checked": len(st["numeric_audit"].checks),\n'
        '            "numeric_contradicted": '
        'len(st["numeric_audit"].contradictions),\n'
        '            "numeric_unverified": '
        'len(st["numeric_audit"].unverified)',
    )
    _set(notebook_cells[c1_idx], c1_src)
    # Table 1 for the supplemental report is generated from the actual
    # integrated run, not copied from a prior report or an invented sample.
    notebook_cells.insert(
        c1_idx + 1,
        _code(
            "from pathlib import Path\n"
            'table1_path = Path("Results/table1_integrated_live_run.csv")\n'
            "table1_path.parent.mkdir(parents=True, exist_ok=True)\n"
            "results.to_csv(table1_path, index=False)\n"
            'print("Table 1 saved:", table1_path.resolve())\n'
            'print("These are fresh integrated-run measurements; copy these '
            'values to the report.")\n'
            "print(results.to_string(index=False))\n"
        ),
    )
    chart_idx = _find(
        notebook_cells,
        "Agent beats the single-prompt baseline on every ticker",
    )
    _set(
        notebook_cells[chart_idx],
        _source(notebook_cells[chart_idx]).replace(
            "Agent beats the single-prompt baseline on every ticker",
            "Rubric comparison: no-tools baseline and integrated agent",
        ),
    )
    original_b10 = _find(notebook_cells, "Run 1 final score:")
    # The cell may be the original Part B10 memory scoring comparison.
    b10_source = _source(notebook_cells[original_b10])
    if "Run 1 final score:" in b10_source:
        _set(
            notebook_cells[original_b10],
            b10_source.replace(
                'state["history"][-1]["average"]',
                'state["evaluation"].average',
            ).replace(
                'state2["history"][-1]["average"]',
                'state2["evaluation"].average',
            ),
        )
    memory_idx = _find(notebook_cells, '"memory": "off"')
    memory_src = _source(notebook_cells[memory_idx])
    _set(
        notebook_cells[memory_idx],
        memory_src.replace(
            'st_off["history"][-1]["average"]', 'st_off["evaluation"].average'
        ).replace(
            'st_on["history"][-1]["average"]', 'st_on["evaluation"].average'
        ),
    )

    # Insert paired policy replay following the existing memory ablation and
    # timing table in Part C, before the limitations subsection.
    limitations_idx = _find(notebook_cells, "## C2. Limitations")
    _set(
        notebook_cells[limitations_idx],
        _source(notebook_cells[limitations_idx]).replace(
            "## C2. Limitations", "## C3. Limitations"
        )
        + "\n- The numeric audit recognizes only a small fraction of "
        "arbitrary prose and cannot certify the brief.\n"
        "- A gate replay compares decisions on recorded scores, not two "
        "independent LLM evaluations.\n"
        "- The LLM reviewer is nondeterministic and can produce different "
        "results in another run.\n",
    )
    c2_cells = [
        _md(PART_C_GATE_NOTE),
        _code(C_GATE_CODE),
        _md(COUNTERFACTUAL_NOTE),
        _code(COUNTERFACTUAL_CODE),
        _md(RECORDED_NOTE),
    ]
    notebook_cells[limitations_idx:limitations_idx] = c2_cells

    # Clarify the assumptions in Part C evaluation text.
    intro_idx = _find(
        notebook_cells, "Part B showed one evaluator-optimizer loop"
    )
    _set(
        notebook_cells[intro_idx],
        _source(notebook_cells[intro_idx])
        + "\nIn this branch, Part B and the C1 baseline experiment use the "
        "reviewed "
        "policy on the same LLM rubric. Policy C2 is a replay on those "
        "recorded observations, not an independent second model run.\n",
    )
    _set(notebook_cells[-1], SUMMARY)

    # Normalize cell IDs for Jupyter notebook format 4.5 and later.
    for index, cell in enumerate(notebook_cells):
        if not cell.get("id"):
            name = f"{index}|{cell['cell_type']}|{_source(cell)}".encode()
            cell["id"] = hashlib.sha256(name).hexdigest()[:12]
    return final
