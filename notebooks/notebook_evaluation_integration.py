def _source(cell: dict) -> str:
    source = cell.get("source", "")
    return "".join(source) if isinstance(source, list) else source


def _set(cell: dict, value: str) -> None:
    cell["source"] = value


def _md(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": text}


def _code(text: str) -> dict:
    return {
        "cell_type": "code",
        "metadata": {},
        "source": text,
        "outputs": [],
        "execution_count": None,
    }


def _find(cells: list[dict], text: str) -> int:
    hits = [i for i, cell in enumerate(cells) if text in _source(cell)]
    if len(hits) != 1:
        raise ValueError(
            f"Expected exactly one notebook cell containing {text!r}; "
            f"found {hits}"
        )
    return hits[0]


